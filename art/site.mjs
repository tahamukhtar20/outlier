// Generates src/art.gen.ts: every illustration the site uses, as SVG strings.
import { writeFileSync } from "node:fs";
import { handDefs, robotHand } from "./hand.mjs";
import { aiHead, bolt, gears, pieceDefs } from "./pieces.mjs";
import { ICONS, logo, stamp, underline } from "./icons.mjs";
import { TEAM, avatar } from "./avatars.mjs";
import { INTRO_CSS, heroScene } from "./scene.mjs";

const svg = (w, h, body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" aria-hidden="true">${body}</svg>`;
const defs = (p) => `<defs>${handDefs(p)}${pieceDefs(p)}</defs>`;

const out = {
  hero: heroScene("hs"),
  about: svg(560, 560, `${defs("ab")}<defs><linearGradient id="abbgfade" x1="0" x2="0" y1="0" y2="1"><stop offset="0" stop-color="#07070c" stop-opacity="0"/><stop offset="1" stop-color="#07070c"/></linearGradient></defs>
    <circle cx="190" cy="170" r="150" fill="url(#abbrand)" filter="url(#abbig)" opacity=".22"/>
    <g class="spin" transform="translate(140 130) scale(1.8)">${gears("ab")}</g>
    <path d="M262 318 C 248 290 240 270 232 250" stroke="#c4b5fd" stroke-width="2.4" stroke-dasharray="2 8" stroke-linecap="round" fill="none"/>
    <g transform="translate(400 600) rotate(-32) scale(1.25)">${robotHand("ab", "point", { arm: 200 })}</g>
    <rect x="0" y="470" width="560" height="90" fill="url(#abbgfade)"/>`),
  palm: svg(640, 420, `${defs("pm")}<circle cx="300" cy="120" r="54" fill="url(#pmbrand)" filter="url(#pmbig)" opacity=".7"/>
    <circle class="orb" cx="300" cy="120" r="30" fill="url(#pmbrand)"/><circle cx="290" cy="110" r="10" fill="#fff" opacity=".7"/>
    <g transform="translate(560 300) rotate(-80)">${robotHand("pm", "open", { arm: 260 })}</g>`),
  aiHead: svg(400, 400, `${defs("ah")}${aiHead("ah")}`),
  bolt: svg(200, 200, `${defs("bt")}<g transform="translate(100 100)">${bolt("bt")}</g>`),
  stamp: stamp("st"),
  logo: logo("lg"),
  underline: underline("ul"),
};
const icons = Object.fromEntries(Object.entries(ICONS).map(([k, draw]) => [k, draw(`ic${k}`)]));
const avatars = Object.fromEntries(TEAM.map((p, i) => [p.name, avatar(p, `av${i}`)]));

// Strip the root width/height so CSS sizes everything.
const clean = (s) => s.replace(/<svg([^>]*?) width="\d+" height="\d+"/, "<svg$1");
const fix = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, clean(v)]));

writeFileSync(
  new URL("../src/art.gen.ts", import.meta.url),
  `// Generated by art/site.mjs. Do not edit by hand; change the generators and run npm run art.\n` +
    `export const ART = ${JSON.stringify(fix(out))} as const;\n` +
    `export const ICONS = ${JSON.stringify(fix(icons))} as Record<string, string>;\n` +
    `export const AVATARS = ${JSON.stringify(fix(avatars))} as Record<string, string>;\n` +
    `export const INTRO_CSS = ${JSON.stringify(INTRO_CSS)};\n`,
);
console.log("art.gen.ts written");
